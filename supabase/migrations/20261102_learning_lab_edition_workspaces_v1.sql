-- Additive, private, non-scoring future premium formative evidence storage.
-- This migration creates NO subscription grants, member rights or checkout.
BEGIN;
CREATE TABLE IF NOT EXISTS public.gu_learning_lab_edition_workspaces_v1 (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  family text NOT NULL CHECK (family IN ('learning','lab')),
  edition text NOT NULL CHECK (edition IN ('ADVANCED','PROFESSIONAL','ENTERPRISE')),
  case_key text NOT NULL CHECK (char_length(case_key) BETWEEN 3 AND 80 AND case_key ~ '^[A-Za-z0-9_-]+$'),
  activity text NOT NULL CHECK (activity IN ('advanced_formative_review','decision_replay_review','chronological_validation')),
  summary jsonb NOT NULL CHECK (jsonb_typeof(summary)='object' AND octet_length(summary::text)<=16384),
  revision integer NOT NULL DEFAULT 1 CHECK (revision>=1),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(user_id,family,edition,case_key),
  CONSTRAINT gu_edition_workspace_activity_matches_edition_v1
    CHECK ((edition='ADVANCED' AND activity='advanced_formative_review')
      OR (edition='PROFESSIONAL' AND activity='decision_replay_review')
      OR (edition='ENTERPRISE' AND activity='chronological_validation'))
);
CREATE INDEX IF NOT EXISTS gu_learning_lab_edition_workspaces_user_updated_v1
  ON public.gu_learning_lab_edition_workspaces_v1(user_id,updated_at DESC);
ALTER TABLE public.gu_learning_lab_edition_workspaces_v1 ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.gu_learning_lab_edition_workspaces_v1 FROM PUBLIC,anon,authenticated;
GRANT SELECT,INSERT,UPDATE,DELETE ON public.gu_learning_lab_edition_workspaces_v1 TO service_role;
-- No public/authenticated RLS policies: only an authenticated Cloudflare API
-- with verified tool, subscription, expiry, family and release grant may read.
-- Retained records do not become accessible after grant expiry or downgrade.
COMMENT ON TABLE public.gu_learning_lab_edition_workspaces_v1 IS
 'Private member-specific ungraded research evidence snapshots, no grading, no member direct grants or public content.';
COMMIT;
