import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {runInNewContext} from 'node:vm';
const s={Math,Number,String,Array,Object,Set,RegExp};s.globalThis=s;
runInNewContext(readFileSync('assets/js/crownlight-scanner-rules-v1.js','utf8'),s);
const E=s.CrownlightScannerRulesV1;
const r=(field,op,value)=>({type:'rule',field,op,value});
const g=(op,...children)=>({type:'group',op,children});
const a={symbol:'AAA',price:5,change_pct:8,volume:500000,rvol:3,float:10000000,spread_pct:1,vwap:4.5,day_high:5.5,change_5m_pct:-2,trades:500};
const interval=g('AND',r('change_5m_pct','GTE',-3),r('change_5m_pct','LTE',0));
assert.equal(E.evaluate(E.validate(interval),a),true);
for(const x of [-3,0])assert.equal(E.evaluate(E.validate(interval),{...a,change_5m_pct:x}),true);
for(const x of [-3.01,0.01])assert.equal(E.evaluate(E.validate(interval),{...a,change_5m_pct:x}),false);
assert.equal(E.evaluate(E.validate(g('OR',r('price','GTE',10),r('trades','GTE',500))),a),true);
assert.equal(E.evaluate(E.validate({type:'not',child:r('trades','GTE',300)}),{...a,trades:''}),null);
assert.equal(E.evaluate(E.validate(g('OR',r('price','GTE',10),r('trades','GTE',300))),{...a,trades:''}),null);
assert.equal(E.evaluate(E.validate(g('AND',r('price','LTE',3),r('trades','GTE',300))),{...a,trades:''}),false);
assert.equal(E.evaluate(E.validate({type:'rule',field:'price',op:'GTE',compareField:'vwap'}),a),true);
assert.equal(E.evaluate(E.validate({type:'rule',field:'price',op:'BETWEEN',value:5,maxValue:6}),a),true);
assert(Math.abs(E.read(a,'vwap_distance_pct')-11.11111111111)<1e-6);
assert.equal(E.read({...a,vwap:''},'vwap_distance_pct'),null);
assert.equal(E.read({...a,day_high:4},'price_below_high_pct'),null);
assert.throws(()=>E.validate(r('__proto__','GT',1)),/Unsupported/);
assert.throws(()=>E.validate(r('price','EQ','Infinity')),/Finite/);
assert.throws(()=>E.validate({type:'rule',field:'price',op:'BETWEEN',value:8,maxValue:2}),/BETWEEN/);
assert.throws(()=>E.validate(g('AND')),/1–12/);
assert.throws(()=>E.validate(g('AND',...Array.from({length:13},()=>r('price','GTE',0)))),/1–12/);
const tooMany=g('AND',...Array.from({length:12},()=>g('AND',...Array.from({length:4},()=>r('price','GTE',0)))));
assert.throws(()=>E.validate(tooMany),/Maximum 40/);
const rows=[a,{...a,symbol:'BBB',change_5m_pct:12},{...a,symbol:'CCC',change_5m_pct:''},
 {...a,symbol:'DDD',change_5m_pct:5},{...a,symbol:'AAA'},
 {...a,symbol:'INVALID',price:''},{...a,symbol:'LOW',change_5m_pct:-3}];
const result=E.analyze(rows,interval);
assert.equal(result.matched,2);
assert.deepEqual(Array.from(result.rows,x=>x.symbol),['AAA','LOW']);
assert.deepEqual(JSON.parse(JSON.stringify(result.rejections)),{invalidInput:1,duplicateTicker:1,missingEvidence:1,failedRule:2});
assert.equal(result.liveFeed,false);
assert.equal(result.tradeAuthorization,false);
assert.equal(result.statisticalEdge,false);
assert.throws(()=>E.analyze(rows,interval,{limit:101}),/Invalid scanner results columns or sort settings/);
assert.throws(()=>E.analyze(rows,interval,{sort:'bogus'}),/Invalid scanner results columns or sort settings/);
assert.throws(()=>E.analyze(Array.from({length:2001},()=>a),interval),/2,000/);
console.log('PASS v1 Crownlight scanner: operator/field/range and tri-state logic, provenance limits');
