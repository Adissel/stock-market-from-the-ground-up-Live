/* Regression: published Knowledge articles open on standalone URLs without exposing bodies. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const get=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const html=get('knowledge-article.html');
const css=get('assets/css/knowledge-article-page-v1.css');
const reader=get('assets/js/knowledge-article-page-v1.js');
const catalog=get('assets/js/knowledge-article-library-v1.js');
const api=get('functions/api/knowledge-library.js');
const db=get('knowledge-database.html');
assert.match(html,/<article id="kal-document"/,'Article must have a real main article landmark');
assert.match(html,/id="kal-article-title"/,'Article must have dedicated title');
assert.match(html,/id="kal-article-content"/,'Article must have protected content area');
assert.match(html,/id="kal-outline"/,'Provide an accessible in-article outline');
assert.match(html,/id="kal-source-list"/,'Provide independent source links');
assert.match(html,/knowledge-article-page-v1.js\?v=1/,'Page must load the versioned article JS');
assert.match(html,/assets\/js\/supabase-client.js/,'Page must load the authenticated website session helper');
assert.match(css,/@media\(max-width:620px\)/,'Mobile layout must stack and retain readable controls');
assert.match(css,/:focus-visible/,'Keyboard focus must be visible');
assert.match(reader,/action:'read'/,'Article body must be requested through secure server action');
assert.match(reader,/authorization:'Bearer '/,'Server-side authorization receives current session token');
assert.match(reader,/status===401/,'Expired sessions must be handled');
assert.match(reader,/status===403/,'Membership lock must be displayed');
assert.match(reader,/renderMarkdown/,'Article body must be formatted for independent full-page reading');
assert(!reader.includes('innerHTML'),'Never inject untrusted Markdown as live HTML');
assert.match(reader,/textContent/,'Only safe DOM text nodes may render article body');
assert.match(reader,/history\.replaceState/,'Old UUID deep links should resolve to canonical slug URLs');
assert.match(catalog,/\/knowledge-article.html\?slug=/,'Catalog cards must use a separate page');
assert.match(catalog,/location\.replace\('\/knowledge-article.html\?article='/,'Preserve previously issued article deep links');
assert(!catalog.includes('body_markdown'),'Public catalog must not contain full article text');
assert.match(db,/knowledge-article-library-v1.js\?v=2/,'Catalog script cache version must be advanced');
assert.match(api,/slug=eq\./,'Server read must accept stable article slugs');
assert.match(api,/id=eq\./,'Server read must continue accepting UUID deep links');
assert.match(api,/status=eq.published&is_visible=eq.true&deleted_at=is.null/,'Reader cannot return unpublished articles');
assert.match(api,/row\.access_plans\.some/,'Eligibility remains server-controlled');
assert.match(api,/role_code=in\.\(OWNER,ADMIN\)/,'Only verified Owner and Admin roles bypass paid tier for review');
assert(!api.includes('user_metadata?.membership'),'User-editable metadata is never entitlement evidence');
console.log('PASS: dedicated article pages, secure slug/UUID reader, membership gating, safe rendering, mobile/keyboard support and legacy links.');
