/* Owner/Admin design-only membership variant and precise OHLC tests. */
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source=fs.readFileSync('assets/js/prototype-membership-builder-v1.js','utf8');
new vm.Script(source,{filename:'prototype-membership-builder-v1.js'});
const storage=new Map();
const stub={window:{},document:{getElementById:()=>null},localStorage:{
 setItem:(k,v)=>storage.set(k,v),getItem:k=>storage.get(k)||null
},structuredClone:v=>JSON.parse(JSON.stringify(v))};
vm.runInNewContext(source,stub);
const api=stub.window.CrownlightClassroomMemberships;
assert(api,'Membership preview module must register');
const codes=Array.from(api.memberships(),x=>x.code);
assert.equal(codes.length,8,'Free, Founding 14/30/60, Full Monthly/Annual, Lifetime and OnDemand');
assert.deepEqual(codes,['FREE','FOUNDING_14','FOUNDING_30','FOUNDING_60','FULL_MONTHLY','FULL_ANNUAL','LIFETIME','ONDEMAND_MONTHLY']);
assert.equal(api.presets().length,20,'20 different adjustable presets required');
assert.equal(new Set(Array.from(api.presets(),x=>x.id)).size,20,'each preset identity must be unique');
api.init({userId:'test-owner',onChange:()=>{}});
api.changeMembership('FOUNDING_60');api.adjust('barWidth',33);api.adjust('detail','Expert');api.selectPreset('full-detail-bars');
api.adjust('barWidth',33);
api.changeMembership('FREE');api.adjust('barWidth',8);api.adjust('detail','Clean');
api.changeMembership('FULL_ANNUAL');api.selectPreset('accessibility-first');api.adjust('chartHeight',600);
api.changeMembership('FOUNDING_60');
assert.equal(api.selected().barWidth,33);
assert.equal(api.selected().detail,'Expert');
assert.equal(api.save(),true,'local design state must be saveable');
api.clear();
api.init({userId:'test-owner',onChange:()=>{}});
assert.equal(api.membership().code,'FOUNDING_60','return to selected saved membership');
assert.equal(api.selected().barWidth,33);
api.changeMembership('FREE');assert.equal(api.selected().barWidth,8,'Free must preserve its own saved draft');
api.changeMembership('FULL_ANNUAL');assert.equal(api.selected().chartHeight,600,'Annual has its own draft');
api.changeMembership('ONDEMAND_MONTHLY');assert.equal(api.selected().id,'replay-control','separate replay default');
api.changeMembership('INVALID_PLAN');assert.equal(api.membership().code,'ONDEMAND_MONTHLY','unregistered codes cannot select a membership');
api.adjust('barWidth',999);assert.equal(api.selected().barWidth,36,'chart widths must be bounded');
api.adjust('chartHeight',-100);assert.equal(api.selected().chartHeight,260);
const bars=[{t:'09:30',open:10,high:10.5,low:9.8,close:10.3,volume:1500},{t:'09:31',open:10.3,high:10.6,low:10.2,close:10.4,volume:2000}];
const detail=api.analyze(bars,0);
assert.ok(detail);assert.equal(Number(detail.range.toFixed(2)),0.7);
assert.equal(Number(detail.body.toFixed(2)),0.3);
assert.equal(Number(detail.upper.toFixed(2)),0.2);
assert.equal(Number(detail.lower.toFixed(2)),0.2);
assert.equal(detail.volume,1500);assert.equal(detail.vsPrevious,null);
assert.equal(api.analyze(bars,1).vsPrevious,0.1+0.00000000000000142);
assert.equal(api.analyze([{t:'x',open:10,close:12,high:11,low:9}],0),null,'invalid OHLC rejected');
const chart=api.chartOptions(bars);
assert.ok(chart.barWidth>=6&&chart.barWidth<=36);
assert.ok(chart.itemStyle.borderWidth>=1&&chart.itemStyle.borderWidth<=5);
assert.match(chart.tooltip([{dataIndex:0}]),/09:30/);
assert.match(source,/Same depth of instruction|same depth of instruction|All entitled learners receive the same depth/i);
assert.doesNotMatch(source,/\/api\/(?:checkout|stripe)|\.from\(['"]platform_plans['"]\)|session\.access_token/,'design must not implement membership or charge mutation');
const html=fs.readFileSync('prototype.html','utf8');
assert.ok(html.includes('id="pt-membership"'));
assert.ok(html.indexOf('prototype-membership-builder-v1.js')<html.indexOf('prototype-center-v1.js'));
assert.ok(html.includes('id="pt-bar-inspector"'));
const main=fs.readFileSync('assets/js/prototype-center-v1.js','utf8');
assert.match(main,/CrownlightClassroomMemberships.*?\.init/);
assert.match(main,/CrownlightClassroomMemberships\?\.render/);
assert.match(main,/member\?\.inspector/);
console.log('PASS: Eight separate membership classroom profiles, 20 presets, persisted isolated drafts, bounded OHLC metrics, read-only design and chart integration.');
