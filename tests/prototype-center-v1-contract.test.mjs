new vm.Script(router,{filename:'route-policy.js'});
assert.match(html,/data-route-access="staff"/);
assert.match(html,/<section id="pt-app" hidden/);
assert.match(html,/noindex,nofollow/);
assert.ok(router.includes("'prototype'"),'staff classification');
assert.match(headers,/\/prototype\.html\s+Cache-Control: private, no-store/);
assert.ok(admin.includes('/assets/js/prototype-admin-link-v1.js'),'Admin entry included');
assert.ok(shortcut.includes("roles.includes('SHOWCASE_VIEWER')"),'showcase shortcut denied');
assert.match(js,/api\/admin\?action=context/);
assert.ok(js.includes("roles.includes('SHOWCASE_VIEWER')"),'Showcase explicitly excluded');
for(const role of ['OWNER','ADMIN','TECH_ADMIN'])assert.ok(js.includes("'"+role+"'"));
assert.ok(js.includes("perms.includes('control_panel.access')"),'staff permission required');
assert.ok(js.includes("await sb.auth.getUser()"),'Supabase user verification');
assert.ok(js.includes("location.replace('/signin.html"),'signed-out redirect');
assert.match(css,/prefers-reduced-motion/);
