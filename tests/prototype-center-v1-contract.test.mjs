import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const read=p=>fs.readFileSync(p,'utf8');
const html=read('prototype.html'),js=read('assets/js/prototype-center-v1.js'),css=read('assets/css/prototype-center-v1.css');
const router=read('assets/js/route-policy.js'),headers=read('_headers'),admin=read('admin.html'),shortcut=read('assets/js/prototype-admin-link-v1.js');
