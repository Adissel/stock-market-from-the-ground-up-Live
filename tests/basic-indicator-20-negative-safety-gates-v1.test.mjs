import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),m=require('../assets/js/learning-indicators-v1.js');
test('01 EMA rejects insufficient closes',()=>{assert.ok(m.ema([1,2],3)===null);});
test('02 EMA rejects period less than two',()=>{assert.ok(m.ema([1,2,3],1)===null);});
test('03 EMA rejects nonfinite price',()=>{assert.ok(m.ema([1,NaN,3],2)===null);});
test('04 EMA rejects unsafe period',()=>{assert.ok(m.ema([1,2,3],101)===null);});
test('05 RSI rejects insufficient price changes',()=>{assert.ok(m.rsi([10,11,12],3)===null);});
test('06 RSI rejects negative prices',()=>{assert.ok(m.rsi([10,-11,12,13],3)===null);});
test('07 RSI flat price is 50',()=>{assert.ok(m.rsi([10,10,10,10],3).history[3]===50);});
test('08 RSI monotonic rise is 100',()=>{assert.ok(m.rsi([10,11,12,13],3).history[3]===100);});
test('09 MACD rejects slow-fast inversion',()=>{assert.ok(m.macd([1,2,3,4,5,6,7],5,3,2)===null);});
test('10 MACD rejects incomplete signal warmup',()=>{assert.ok(m.macd([1,2,3,4,5,6],3,5,3)===null);});
test('11 MACD valid signal first appears at completed warmup',()=>{assert.ok(m.macd([1,2,3,4,5,6,7],3,5,3).signal.slice(0,6).every(x=>x===null));});
test('12 ATR rejects missing bar',()=>{assert.ok(m.atr([{h:11,l:9,c:10},null],2)===null);});
test('13 ATR rejects invalid candle bound',()=>{assert.ok(m.atr([{h:10,l:11,c:10},{h:11,l:9,c:10}],2)===null);});
test('14 ATR rejects insufficient bars',()=>{assert.ok(m.atr([{h:11,l:9,c:10}],2)===null);});
test('15 Bollinger rejects insufficient closes',()=>{assert.ok(m.bollinger([1,2],3,2)===null);});
test('16 Bollinger rejects invalid sigma multiplier',()=>{assert.ok(m.bollinger([1,2,3],3,0)===null);});
test('17 Bollinger initial range stays null',()=>{assert.ok(m.bollinger([10,12,14],3,2).upper[0]===null);});
test('18 Study selection rejects unknown Lab',()=>{assert.ok(m.select({labId:'UNREGISTERED',topic:'RSI'})===null);});
test('19 Study selection rejects mismatched ATR subject',()=>{assert.ok(m.select({labId:'DT-C19-L03',topic:'Bollinger'})===null);});
test('20 Ungraded formative method rejects inaccessible source',()=>{assert.ok(m.assess({studyId:'rsi',inputs:['1','2','3'],mode:'graded',stage:'practice',provenance:'fictional_authored'}).officialGrade===false);});
