import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const read=p=>readFileSync(p,'utf8');
const html=read('prototype.html'),src=read('src/prototype/PrototypeExperiences.tsx'),css=read('assets/css/prototype-experiences-v1.css'),boot=read('assets/js/prototype-experiences-boot-v1.js'),build=read('scripts/build-pages.sh');
for(const page of ['a','b','c'])assert.ok(html.includes('/prototype.html?experience='+page),'Missing protected option '+page);
assert.match(html,/id="pt-app" hidden/);
assert.match(html,/data-route-access="staff"/);
assert.match(boot,/protectedApp\.hidden/);
assert.match(boot,/MutationObserver/);
assert.match(boot,/mountExperienceSuite/);
for(const code of ['FREE','PICK_WHAT_YOU_WANT','FOUNDING_14','FOUNDING_30','FOUNDING_60','FULL_MONTHLY','FULL_ANNUAL','LIFETIME','ONDEMAND_MONTHLY'])assert.ok(src.includes("code:'"+code+"'"),'Missing existing product identity '+code);
for(const theme of ['quantum','neon','green','ember','aurora','onyx'])assert.ok(css.includes('.cx-theme-'+theme),'Missing design theme '+theme);
for(const label of ['Build & Understand a Candlestick','VWAP','EXACT TRADE-PRINT VWAP','OHLCV VWAP proxy'])assert.ok(src.toLowerCase().includes(label.toLowerCase()),'Missing precision teaching '+label);
assert.match(src,/no future bars beyond the replay boundary/);
assert.match(src,/function dataFor\(reveal:number\)/);
assert.match(src,/setReveal\(Math\.max/);
assert.match(src,/onDragStart/);
assert.match(src,/type="range"/);
assert.match(boot,/typeof module.mountExperienceSuite/);
assert.match(src,/Founders Commons/);
for(const code of ['FOUNDING_14','FOUNDING_30','FOUNDING_60'])assert.match(src,new RegExp("code:'"+code+"'.*?founder:true,commons:true"),'All Founders Commons plan flags must be included');
assert.match(src,/Design\/governance voting/);
assert.match(src,/plan.code==='FOUNDING_60'/,'Governance voting must remain exclusive');
assert.match(src,/PICK_WHAT_YOU_WANT:.*?defaultStudio:'Standard'/,'Pick What You Want gets Basic by default');
assert.match(src,/identical instructional quality/i);
assert.match(build,/PrototypeExperiences\.tsx/);
assert.match(build,/--noEmit --strict/);
assert.match(build,/prototype-experiences-v1\.bundle\.js/);
assert.match(css,/prefers-reduced-motion/);
// The protected synthetic prototype may load its public, static first-party tutor
// guide, but must never issue dynamic entitlement, wallet, brokerage or user APIs.
const allFetches=(src.match(/\bfetch\s*\(/g)||[]).length;
const approvedStaticFetches=(src.match(/\bfetch\s*\(\s*'\/data\/tutor-indicator-study-v1\.json'\s*,\s*\{\s*cache:'no-store',credentials:'same-origin'\s*\}/g)||[]).length;
assert.equal(approvedStaticFetches,1,'Expect exactly one immutable-path same-origin guide load');
assert.equal(allFetches,approvedStaticFetches,'No remote, dynamic, entitlement, wallet or brokerage fetch calls allowed');
console.log('PASS: three protected pages, nine plan identities, six themes, teaching and replay boundaries, TypeScript build and local-only interactions');
